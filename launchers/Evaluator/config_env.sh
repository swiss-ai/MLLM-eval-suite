#!/usr/bin/env bash
# Shared NeMo Evaluator template environment helpers.

evaluator_write_env_file() {
  local task="$1"
  local output_dir="$2"
  local env_path="$3"
  local entry name value

  mkdir -p "${output_dir}"
  : >"${env_path}"

  local env_spec=(
    "NEL_SERVICE_TYPE|${SERVICE_TYPE}"
    "NEL_APERTUS_MODEL|${MODEL_PATH}"
    "NEL_APERTUS_SERVED_MODEL_NAME|${SERVED_MODEL_NAME}"
    "NEL_APERTUS_PROTOCOL|${SERVICE_PROTOCOL}"
    "NEL_APERTUS_PORT|${PORT}"
    "NEL_APERTUS_TP|${TP_SIZE}"
    "NEL_APERTUS_PP|${PP_SIZE}"
    "NEL_APERTUS_DP|${DP_SIZE}"
    "NEL_APERTUS_NUM_NODES|${NUM_NODES}"
    "NEL_APERTUS_STARTUP_TIMEOUT|${STARTUP_TIMEOUT}"
    "NEL_APERTUS_TEMPERATURE|${TEMPERATURE}"
    "NEL_APERTUS_TOP_P|${TOP_P}"
    "NEL_APERTUS_MAX_TOKENS|${MAX_TOKENS}"
    "NEL_APERTUS_SEED|${SEED}"
    "NEL_APERTUS_STOP|${STOP}"
    "NEL_APERTUS_FREQUENCY_PENALTY|${FREQUENCY_PENALTY}"
    "NEL_APERTUS_PRESENCE_PENALTY|${PRESENCE_PENALTY}"
    "NEL_APERTUS_MODELS_CACHE|${MODELS_CACHE}"
    "NEL_APERTUS_TOKENIZER|${TOKENIZER_PATH}"
    "NEL_APERTUS_CHAT_TEMPLATE|${CHAT_TEMPLATE}"
    "NEL_APERTUS_MAX_MODEL_LEN|${MAX_MODEL_LEN}"
    "NEL_APERTUS_MAX_NUM_BATCHED_TOKENS|${MAX_NUM_BATCHED_TOKENS}"
    "NEL_APERTUS_GPU_MEMORY_UTILIZATION|${GPU_MEMORY_UTILIZATION}"
    "NEL_APERTUS_HF_OVERRIDES|${HF_OVERRIDES}"
    "NEL_BENCHMARK_NAME|${task}"
    "NEL_BENCHMARK_MAX_PROBLEMS|${MAX_PROBLEMS}"
    "NEL_BENCHMARK_MAX_CONCURRENT|${MAX_CONCURRENT}"
    "NEL_BENCHMARK_REPEATS|${REPEATS}"
    "NEL_BENCHMARK_TIMEOUT|${BENCHMARK_TIMEOUT}"
    "NEL_BENCHMARK_FEWSHOT|${BENCHMARK_FEWSHOT}"
    "NEL_BENCHMARK_CONTEXT_WINDOW|${BENCHMARK_CONTEXT_WINDOW}"
    "NEL_BENCHMARK_SKIP_FAILED|${BENCHMARK_SKIP_FAILED}"
    "NEL_BENCHMARK_MAX_SYSTEM_RETRIES|${BENCHMARK_MAX_SYSTEM_RETRIES}"
    "NEL_BENCHMARK_INSTRUCTION_TEMPLATE|${BENCHMARK_INSTRUCTION_TEMPLATE}"
    "NEL_BENCHMARK_VERIFIER|${BENCHMARK_VERIFIER}"
    "NEL_BENCHMARK_SHUFFLE_SEED|${BENCHMARK_SHUFFLE_SEED}"
    "NEL_BENCHMARK_SANDBOX|${BENCHMARK_SANDBOX}"
    "NEL_BENCHMARK_PARAMS|${BENCHMARK_PARAMS}"
    "NEL_SOLVER_TYPE|${SOLVER_TYPE}"
    "NEL_SOLVER_SERVICE|${SOLVER_SERVICE}"
    "NEL_SOLVER_SYSTEM_PROMPT|${SOLVER_SYSTEM_PROMPT}"
    "NEL_SOLVER_TEMPERATURE|${SOLVER_TEMPERATURE}"
    "NEL_SOLVER_TOP_P|${SOLVER_TOP_P}"
    "NEL_SOLVER_MAX_TOKENS|${SOLVER_MAX_TOKENS}"
    "NEL_SOLVER_SEED|${SOLVER_SEED}"
    "NEL_SOLVER_STOP|${SOLVER_STOP}"
    "NEL_SOLVER_FREQUENCY_PENALTY|${SOLVER_FREQUENCY_PENALTY}"
    "NEL_SOLVER_PRESENCE_PENALTY|${SOLVER_PRESENCE_PENALTY}"
    "NEL_SCORING_INCLUDE_DEFAULTS|${SCORING_INCLUDE_DEFAULTS}"
    "NEL_SCORING_METRICS|${SCORING_METRICS}"
    "NEL_SCORING_PRIMARY|${SCORING_PRIMARY}"
    "NEL_PROGRESS_INTERVAL|${PROGRESS_INTERVAL}"
    "NEL_OUTPUT_DIR|${output_dir}"
    "NEL_OUTPUT_TIMESTAMPED|${OUTPUT_TIMESTAMPED}"
    "NEL_OUTPUT_EXPORT|${OUTPUT_EXPORT}"
    "NEL_OUTPUT_EXPORT_CONFIG|${OUTPUT_EXPORT_CONFIG}"
    "NEL_HARBOR_AGENT|${HARBOR_AGENT}"
    "NEL_HARBOR_AGENT_KWARGS|${HARBOR_AGENT_KWARGS}"
    "NEL_HARBOR_CONTAINER_ENV|${HARBOR_CONTAINER_ENV}"
    "NEL_HARBOR_RUN_TIMEOUT|${HARBOR_RUN_TIMEOUT}"
    "NEL_HARBOR_CMD_TIMEOUT|${HARBOR_CMD_TIMEOUT}"
    "NEL_HARBOR_TIMEOUT_STRATEGY|${HARBOR_TIMEOUT_STRATEGY}"
    "NEL_HARBOR_MAX_AGENT_TIMEOUT|${HARBOR_MAX_AGENT_TIMEOUT}"
    "NEL_HARBOR_SKILL|${HARBOR_SKILL}"
    "NEL_HARBOR_SKILL_DIR|${HARBOR_SKILL_DIR}"
    "NEL_OPENCLAW_THINKING|${OPENCLAW_THINKING}"
    "NEL_OPENCLAW_CONTEXT_WINDOW|${OPENCLAW_CONTEXT_WINDOW}"
    "NEL_OPENCLAW_MAX_CONCURRENT|${OPENCLAW_MAX_CONCURRENT}"
    "NEL_OPENCLAW_IDLE_TIMEOUT_SECONDS|${OPENCLAW_IDLE_TIMEOUT_SECONDS}"
    "NEL_OPENCLAW_RUN_TIMEOUT|${OPENCLAW_RUN_TIMEOUT}"
    "NEL_OPENCLAW_TIMEOUT_STRATEGY|${OPENCLAW_TIMEOUT_STRATEGY}"
    "NEL_OPENCLAW_MAX_AGENT_TIMEOUT|${OPENCLAW_MAX_AGENT_TIMEOUT}"
    "NEL_OPENCLAW_WEB_SEARCH_PROVIDER|${OPENCLAW_WEB_SEARCH_PROVIDER}"
    "NEL_OPENCLAW_CONFIG_PATH|${OPENCLAW_CONFIG_PATH}"
    "NEL_OPENCLAW_SKIP_PREFLIGHT|${OPENCLAW_SKIP_PREFLIGHT}"
    "NEL_OPENCLAW_BIN|${OPENCLAW_BIN}"
  )

  for entry in "${env_spec[@]}"; do
    name="${entry%%|*}"
    value="${entry#*|}"
    [[ -n "${value}" ]] || continue
    printf 'export %s=%s\n' "${name}" "$(shell_quote "${value}")" >>"${env_path}"
  done
}
